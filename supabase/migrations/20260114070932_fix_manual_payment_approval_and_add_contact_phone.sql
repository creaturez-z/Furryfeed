-- Drop and recreate the approve_manual_payment function
DROP FUNCTION IF EXISTS approve_manual_payment(uuid, uuid, text);

CREATE OR REPLACE FUNCTION approve_manual_payment(
  p_transaction_id uuid,
  p_admin_id uuid,
  p_admin_notes text
)
RETURNS jsonb AS $$
DECLARE
  v_transaction RECORD;
  v_wallet_id uuid;
  v_new_balance numeric(10, 2);
BEGIN
  -- Get transaction details
  SELECT * INTO v_transaction
  FROM manual_payment_transactions
  WHERE id = p_transaction_id;
  
  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'error', 'Transaction not found');
  END IF;
  
  IF v_transaction.status != 'pending' THEN
    RETURN jsonb_build_object('success', false, 'error', 'Transaction already processed');
  END IF;
  
  -- Update transaction status
  UPDATE manual_payment_transactions
  SET 
    status = 'approved',
    admin_notes = p_admin_notes,
    reviewed_by = p_admin_id,
    reviewed_at = now(),
    updated_at = now()
  WHERE id = p_transaction_id;
  
  -- Get or create wallet
  SELECT id, balance INTO v_wallet_id, v_new_balance
  FROM wallets
  WHERE customer_id = v_transaction.user_id;
  
  IF NOT FOUND THEN
    -- Create wallet if it doesn't exist
    INSERT INTO wallets (customer_id, balance)
    VALUES (v_transaction.user_id, v_transaction.amount)
    RETURNING id, balance INTO v_wallet_id, v_new_balance;
  ELSE
    -- Update existing wallet
    v_new_balance := v_new_balance + v_transaction.amount;
    UPDATE wallets
    SET 
      balance = v_new_balance,
      updated_at = now()
    WHERE id = v_wallet_id;
  END IF;
  
  -- Log the wallet transaction
  INSERT INTO wallet_transactions (
    wallet_id,
    customer_id,
    type,
    amount,
    reason,
    reference_type,
    reference_id
  ) VALUES (
    v_wallet_id,
    v_transaction.user_id,
    'credit',
    v_transaction.amount,
    'Manual payment approved',
    'manual_payment',
    p_transaction_id
  );
  
  -- Log activity
  INSERT INTO activity_logs (
    user_id,
    action,
    entity_type,
    entity_id,
    details
  ) VALUES (
    v_transaction.user_id,
    'wallet_credit',
    'manual_payment',
    p_transaction_id,
    jsonb_build_object(
      'amount', v_transaction.amount,
      'approved_by', p_admin_id,
      'notes', p_admin_notes,
      'new_balance', v_new_balance
    )
  );
  
  -- Update subscription status if linked
  IF v_transaction.subscription_id IS NOT NULL THEN
    UPDATE subscriptions
    SET 
      payment_status = 'paid',
      payment_method = 'manual',
      status = 'active',
      updated_at = now()
    WHERE id = v_transaction.subscription_id
    AND payment_status = 'pending_payment';
    
    -- Generate invoice for the subscription
    -- Note: This will be handled by a trigger or separate call
    -- We'll add a helper function for this
  END IF;
  
  RETURN jsonb_build_object(
    'success', true, 
    'transaction_id', p_transaction_id,
    'new_balance', v_new_balance,
    'subscription_id', v_transaction.subscription_id
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Create helper function to generate invoice after manual payment approval
CREATE OR REPLACE FUNCTION generate_invoice_after_payment()
RETURNS TRIGGER AS $$
DECLARE
  v_subscription_id uuid;
BEGIN
  -- Only proceed if subscription was just activated via manual payment
  IF NEW.payment_status = 'paid' 
     AND OLD.payment_status = 'pending_payment'
     AND NEW.payment_method = 'manual' THEN
    
    -- Check if invoice already exists
    IF NOT EXISTS (
      SELECT 1 FROM invoices 
      WHERE subscription_id = NEW.id
      AND invoice_type = 'subscription'
    ) THEN
      -- Invoice will be generated by the application layer
      -- This trigger just ensures the state is correct
      NULL;
    END IF;
  END IF;
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Create trigger for invoice generation
DROP TRIGGER IF EXISTS trigger_generate_invoice_after_payment ON subscriptions;
CREATE TRIGGER trigger_generate_invoice_after_payment
  AFTER UPDATE ON subscriptions
  FOR EACH ROW
  EXECUTE FUNCTION generate_invoice_after_payment();
